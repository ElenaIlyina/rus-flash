export function textSkillsPage({ kind, heading, backLink, cardId, catalog }) {
  const guide = guides[kind];
  const cards = catalog.cards.filter((card) => card.task === guide.task);
  const refs = guide.words
    .map((word) =>
      cards
        .flatMap((card) => card.dictionarySourceRefs || [])
        .find((ref) => ref.headword === word),
    )
    .filter(Boolean);
  return (
    heading(`РАБОТА С ТЕКСТОМ · №${guide.task}`, guide.title, guide.subtitle) +
    backLink +
    `<article class="panel knowledge-rule" data-text-skill="${kind}">${guide.body}
      <h3>Словарные примеры</h3>${renderDictionaryReferences(refs, cardId)}
      ${kind === "meanings" ? `<p><a class="text-link" href="${esc(paronymListSourceUrl)}#page=1" target="_blank" rel="noopener">ФИПИ · значение слова и контекст, с. 1–2</a></p>` : ""}
      <nav class="rule-links"><a class="text-link" href="#bank?task=${guide.task}&status=verified">К заданиям №${guide.task}</a></nav>
    </article>` +
    backLink
  );
}
