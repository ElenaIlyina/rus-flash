import { esc } from "./ui.js";
import { paronymListSourceUrl } from "./data.js";
import { renderDictionaryReferences } from "./paronyms.js";

export function lexicalNormsPage({ heading, backLink, cardId, catalog }) {
  const examples = ["плеоназм", "тавтология", "пристальный", "поступок"];
  const refs = examples
    .map((word) =>
      catalog.cards
        .filter((card) => card.task === 6)
        .flatMap((card) => card.dictionarySourceRefs || [])
        .find((ref) => ref.headword === word),
    )
    .filter(Boolean);
  const count = catalog.cards.filter((card) => card.task === 6).length;
  return (
    heading(
      "ЛЕКСИКА",
      "Лексические нормы",
      "Убираем лишнее, выбираем точное, сохраняем смысл.",
    ) +
    backLink +
    `<article class="panel knowledge-rule" data-lexical-theory>
      <h2>Сначала прочитайте инструкцию</h2>
      <p>В задании №6 встречаются два действия. Если просят <b>исключить лишнее слово</b>, выпишите удаляемое слово. Если просят <b>заменить неверно употреблённое</b>, запишите замену в нужной форме. Если условие разрешает исключить слово или выражение, учитывайте эту формулировку. Не отправляйте целое предложение вместо ответа.</p>
      <h2>Лишнее слово: что оно добавляет?</h2>
      <p>При плеоназме без необходимости повторяется уже выраженный смысл: «фольклор» — народное творчество, поэтому в нейтральном контексте «народный» может оказаться лишним. При тавтологии повтор того же смысла может поддерживаться однокоренными словами: «правильное правописание».</p>
      <p>Сам по себе одинаковый корень или близкое значение не доказывает ошибки. Уточнение, противопоставление и выразительный повтор могут быть осмысленными. Попробуйте убрать слово и проверьте, потерялась ли нужная информация.</p>
      <h2>Замена: проверяем сочетание целиком</h2>
      <p>Слова сочетаются по значению и по привычному употреблению: «совершить поступок», но «проявить мужество»; «уделить внимание», но «придавать значение». Сохраняйте остальную конструкцию и меняйте именно то слово, которого требует инструкция.</p>
      <h2>Устойчивые выражения</h2>
      <p>Не подменяйте компонент выражения близким по буквальному смыслу словом: начать новую жизнь — «с чистого листа». Этот оборот есть в списке ФИПИ; его форма важна и для выбора ответа.</p>
      <h2>Проверьте результат</h2>
      <ol><li>Перечитайте целое предложение после удаления или замены.</li><li>Сохраните исходную мысль и грамматические связи.</li><li>При замене проверьте род, число, падеж, время и вид.</li><li>Запишите только требуемый ответ. Автопроверка следует сохранённому ключу ФИПИ; словарные и контекстные оговорки приведены в разборах.</li></ol>
      <h3>Источники и примеры</h3>${renderDictionaryReferences(refs, cardId)}
      <nav class="rule-links"><a class="text-link" href="${esc(paronymListSourceUrl)}#page=1" target="_blank" rel="noopener">ФИПИ · лексика и работа со значением, 2025, с. 1–2</a><a class="text-link" href="${esc(paronymListSourceUrl)}#page=11" target="_blank" rel="noopener">ФИПИ · «с чистого листа», с. 11</a><a class="text-link" href="#bank?task=6&status=verified">К заданиям №6 · ${count}</a></nav>
    </article>` +
    backLink
  );
}
