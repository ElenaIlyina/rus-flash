import { renderDictionaryReferences } from "./paronyms.js";

export function wordFormsPage({ heading, backLink, cardId, catalog }) {
  const cards = catalog.cards.filter((card) => card.task === 7);
  const refs = ["плечо", "адрес", "восемьсот", "оба", "лечь", "молодой"]
    .map((word) =>
      cards
        .flatMap((card) => card.dictionarySourceRefs || [])
        .find((ref) => ref.headword === word),
    )
    .filter(Boolean);
  return (
    heading(
      "ГРАММАТИКА",
      "Формы слов",
      "Определяем нужную форму и проверяем её в словосочетании.",
    ) +
    backLink +
    `<article class="panel knowledge-rule" data-word-forms-theory>
      <h2>Что требуется в №7</h2>
      <p>Найдите ошибку в образовании формы выделенного слова. Исправьте именно это слово и запишите его целиком. Не заменяйте всё словосочетание и не меняйте его смысл.</p>
      <h2>Существительные: род, число, падеж</h2>
      <p>Сначала задайте вопрос: «нет чего?» — родительный, «чем?» — творительный. Затем проверьте словарную форму: нет плеч, туфель, яблок, но платьев. У названий профессий окончания тоже различаются: повара, но бухгалтеры.</p>
      <p>Род важен для склонения: тонкий тюль → тюлем; сладкое повидло → с повидлом. Иногда форма зависит от значения: городские адреса, но поздравительные адресы.</p>
      <h2>Сравнение: выбираем один способ</h2>
      <p>Простая сравнительная форма выражает сравнение сама: моложе, красивее, выше. Составная строится со словом «более»: более молодой, более красивый, более высоко. Не соединяйте способы: «более моложе» неверно.</p>
      <p>Если выделено только «МОЛОЖЕ» в сочетании «более МОЛОЖЕ», замените его на «молодой», сохранив «более». Для превосходной степени подходит, например, «наиболее красивый».</p>
      <h2>Числительные: количество или порядок?</h2>
      <p>В количественных числительных от двухсот до девятисот склоняются обе части: триста — трёхсот — трёмстам — тремястами — о трёхстах. Падеж выбирайте по связи с остальными словами, не по созвучию.</p>
      <p>В составном порядковом числительном изменяется только последнее слово: две тысячи двадцать первый год — к две тысячи двадцать первому году. Однословное «двухтысячный» склоняется целиком: в двухтысячном году. Номер «800-й» — восьмисотый.</p>
      <h2>Местоимения и «оба / обе»</h2>
      <p>«Оба» сочетается с мужским и средним родом: оба берега, оба стекла; «обе» — с женским: обе стороны. Поэтому по обоим берегам, но по обеим сторонам. Притяжательное «их» не склоняется: по их расчётам.</p>
      <p>Начальное н- у личного местоимения появляется не после любого предлога: к нему, но наперекор ему. Проверяйте конкретное сочетание.</p>
      <h2>Глаголы и их формы</h2>
      <p>Не выводите все формы механически из одной: бежит — бегут; пеку — печёт; сожгу — сожжёшь. Повелительное наклонение проверяйте отдельно: ляг — лягте; поезжай — поезжайте; съезди — съездите.</p>
      <p>Следите за видом и возвратностью: клал и положил отвечают на разные вопросы; выигравший приз образуется от невозвратного «выиграть». Деепричастие от «приобрести» — приобретя, хотя прошедшее время — приобрёл.</p>
      <h2>Как прочитать словарную запись</h2>
      <p>После заголовочного слова часто даны формы или их окончания. «Плечо, … мн. плечи, плеч» показывает форму родительного множественного; «лечь, … ляг, лягте» — повелительное наклонение. Если нужной формы в короткой статье нет, одно её отсутствие ещё не доказывает ошибку.</p>
      <h3>Словарные примеры</h3>${renderDictionaryReferences(refs, cardId)}
      <p>В ответе сохраняйте нужные род, число и падеж. Автопроверка принимает форму из ключа задания; особенности и допустимые формы в других значениях поясняются в разборе.</p>
      <nav class="rule-links"><a class="text-link" href="#bank?task=7&status=verified">К заданиям №7 · ${cards.length}</a></nav>
    </article>` +
    backLink
  );
}
